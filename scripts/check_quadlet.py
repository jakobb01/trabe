#!/usr/bin/env python3
"""Render the real Quadlet and check its options with the chosen Podman parser."""

import argparse
import json
import os
import shlex
import shutil
import subprocess
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def check(generator: Path, podman: Path) -> dict:
    environment = os.environ | {"QUADLET_UNIT_DIRS": str(ROOT / "deploy/quadlet")}
    commands = []
    with tempfile.TemporaryDirectory(prefix="stockpulse-quadlet-") as directory:
        subprocess.run(
            [str(generator), "-user", directory],
            env=environment,
            check=True,
            capture_output=True,
            text=True,
            timeout=20,
        )
        service = Path(directory) / "stock-agent.service"
        if not service.exists():
            raise ValueError("Quadlet did not generate stock-agent.service.")
        text = service.read_text()
        # Model Podman 4.3's removal behavior: it leaves the CID file behind.
        # Exercise the rendered pre-start command against that leftover state.
        runtime = Path(directory) / "runtime"
        runtime.mkdir()
        cid = runtime / "stock-agent.cid"
        cleanup = []
        for line in text.splitlines():
            if line.startswith("ExecStartPre="):
                command = shlex.split(line.partition("=")[2])
                expanded = [
                    part.replace("%t", str(runtime)).replace("%N", "stock-agent")
                    for part in command
                ]
                if expanded == ["/usr/bin/rm", "-f", str(cid)]:
                    cleanup = expanded
        if not cleanup:
            raise ValueError("Service must clear its own stale CID file before startup.")
        cid.write_text("left-behind-by-podman-4.3")
        for _ in range(3):
            subprocess.run(cleanup, check=True, capture_output=True, timeout=5)
            with cid.open("x") as stream:
                stream.write("simulated-container-id")
            # A simulated stop deliberately does not unlink the file.
        for line in text.splitlines():
            if line.startswith(("ExecStart=", "ExecStop=", "ExecStopPost=")):
                directive, _, value = line.partition("=")
                command = shlex.split(value.lstrip("-"))
                if Path(command[0]).name != "podman" or command[1] not in ("run", "rm"):
                    raise ValueError("Unexpected generated container command.")
                if command[1] == "run":
                    try:
                        timeout = int(command[command.index("--stop-timeout") + 1])
                    except (ValueError, IndexError):
                        raise ValueError(
                            "Service must set an explicit container stop timeout."
                        ) from None
                    if timeout < 60:
                        raise ValueError(
                            "Container stop timeout must allow polling and scan shutdown."
                        )
                if any(option in ("--publish", "-p", "--network=host") for option in command):
                    raise ValueError("The bot must not publish ports or use host networking.")
                # --help must precede the image; after it, it is a container command.
                result = subprocess.run(
                    [str(podman), command[1], "--help", *command[2:]],
                    capture_output=True,
                    text=True,
                    timeout=20,
                )
                if result.returncode:
                    raise ValueError("Installed Podman rejected an option generated by Quadlet.")
                commands.append(
                    {
                        "service": service.name,
                        "directive": directive,
                        "podman_options_accepted": True,
                    }
                )
        if not commands or "WantedBy=default.target" not in text:
            raise ValueError("Generated service is missing its command or boot dependency.")
        negative = subprocess.run(
            [str(podman), "run", "--stockpulse-invalid-option", "--help"],
            capture_output=True,
            text=True,
            timeout=20,
        )
        if negative.returncode == 0:
            raise ValueError("Podman option validation negative control failed.")
    return {
        "commands": commands,
        "unknown_option_rejected": True,
        "published_ports": 0,
        "stale_cid_restart_cycles": 3,
        "stop_timeout_seconds": 60,
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    default_generator = next(
        (
            Path(path)
            for path in (
                "/usr/libexec/podman/quadlet",
                "/usr/lib/podman/quadlet",
                "/usr/lib/systemd/user-generators/podman-user-generator",
            )
            if Path(path).exists()
        ),
        None,
    )
    parser.add_argument("--generator", type=Path, default=default_generator)
    parser.add_argument(
        "--podman", type=Path, default=Path(shutil.which("podman") or "/usr/bin/podman")
    )
    parser.add_argument("--report", type=Path)
    args = parser.parse_args()
    try:
        if args.generator is None:
            raise ValueError("No local Quadlet generator found.")
        report = check(args.generator, args.podman)
        if args.report:
            args.report.parent.mkdir(parents=True, exist_ok=True)
            args.report.write_text(json.dumps(report, indent=2) + "\n")
        print(json.dumps(report, indent=2))
        return 0
    except (ValueError, OSError, subprocess.SubprocessError) as error:
        parser.exit(1, f"Quadlet check failed: {error}\n")


if __name__ == "__main__":
    raise SystemExit(main())
